"""Object storage abstraction for large binary artefacts (samples, evidence, exports).

MySQL keeps metadata, hashes, scope and the object key; the bytes live here. Two adapters:
- `filesystem` (default): files under CR_STORAGE_DIR, directories 0700, files 0600, never executable.
- `minio`: S3-compatible bucket (CR_STORAGE_BUCKET) on CR_MINIO_URL with credentials from the environment.
Keys are generated by the platform (never taken from user input) and validated against KEY_RX.
"""
import hashlib
import os
import re
import tempfile
from abc import ABC, abstractmethod
from collections.abc import Iterator
from dataclasses import dataclass
from functools import lru_cache
from typing import BinaryIO

from app.core.config import get_settings
from app.core.errors import AppError

KEY_RX = re.compile(r"^[a-z0-9][a-z0-9_-]{0,40}(/[A-Za-z0-9._-]{1,128}){1,4}$")
CHUNK = 1024 * 1024


class StorageError(Exception):
    pass


@dataclass
class Spooled:
    """An upload read once into a temporary file while hashing; the caller decides whether to keep it."""
    file: BinaryIO
    size: int
    md5: str
    sha1: str
    sha256: str
    head: bytes  # first 64 KiB for type detection

    def close(self):
        self.file.close()


def spool(src: BinaryIO, max_bytes: int, transform=None) -> Spooled:
    """Copy `src` into a temp file, computing hashes of the ORIGINAL bytes. `transform(chunk, offset)` may neutralise bytes at rest."""
    md5, sha1, sha256 = hashlib.md5(usedforsecurity=False), hashlib.sha1(usedforsecurity=False), hashlib.sha256()
    out = tempfile.TemporaryFile()
    size, head = 0, b""
    while True:
        chunk = src.read(CHUNK)
        if not chunk:
            break
        size += len(chunk)
        if size > max_bytes:
            out.close()
            raise AppError(f"File exceeds the maximum size of {max_bytes // (1024 * 1024)} MB", code="file_too_large", status_code=413)
        if len(head) < 65536:
            head += chunk[: 65536 - len(head)]
        md5.update(chunk)
        sha1.update(chunk)
        sha256.update(chunk)
        out.write(transform(chunk, size - len(chunk)) if transform else chunk)
    if size == 0:
        out.close()
        raise AppError("The file is empty", code="empty_file", status_code=422)
    out.seek(0)
    return Spooled(out, size, md5.hexdigest(), sha1.hexdigest(), sha256.hexdigest(), head)


class Storage(ABC):
    name = "abstract"

    @staticmethod
    def check_key(key: str) -> str:
        if not KEY_RX.match(key) or ".." in key:
            raise StorageError(f"invalid object key {key!r}")
        return key

    @abstractmethod
    def put(self, key: str, fileobj: BinaryIO, size: int) -> None: ...
    @abstractmethod
    def open_iter(self, key: str) -> Iterator[bytes]: ...
    @abstractmethod
    def exists(self, key: str) -> bool: ...
    @abstractmethod
    def delete(self, key: str) -> None: ...
    @abstractmethod
    def status(self) -> dict: ...

    def read_all(self, key: str, limit: int = 256 * 1024 * 1024) -> bytes:
        buf = bytearray()
        for c in self.open_iter(key):
            buf += c
            if len(buf) > limit:
                raise StorageError("object larger than read limit")
        return bytes(buf)

    def sha256(self, key: str) -> tuple[str, int]:
        h, n = hashlib.sha256(), 0
        for c in self.open_iter(key):
            h.update(c)
            n += len(c)
        return h.hexdigest(), n


class FilesystemStorage(Storage):
    name = "filesystem"

    def __init__(self, root: str):
        self.root = os.path.abspath(root)

    def _path(self, key: str) -> str:
        p = os.path.abspath(os.path.join(self.root, self.check_key(key)))
        if not p.startswith(self.root + os.sep):
            raise StorageError("key escapes storage root")
        return p

    def put(self, key, fileobj, size):
        p = self._path(key)
        os.makedirs(os.path.dirname(p), mode=0o700, exist_ok=True)
        tmp = p + ".part"
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        try:
            with os.fdopen(fd, "wb") as f:
                while chunk := fileobj.read(CHUNK):
                    f.write(chunk)
            os.replace(tmp, p)
        except BaseException:
            if os.path.exists(tmp):
                os.unlink(tmp)
            raise

    def open_iter(self, key):
        p = self._path(key)
        if not os.path.isfile(p):
            raise StorageError(f"object {key} not found")
        with open(p, "rb") as f:
            while chunk := f.read(CHUNK):
                yield chunk

    def exists(self, key):
        return os.path.isfile(self._path(key))

    def delete(self, key):
        p = self._path(key)
        if os.path.isfile(p):
            os.unlink(p)

    def status(self):
        try:
            os.makedirs(self.root, mode=0o700, exist_ok=True)
            st = os.statvfs(self.root)
            return {"adapter": self.name, "ok": os.access(self.root, os.W_OK), "free_bytes": st.f_bavail * st.f_frsize}
        except OSError as e:
            return {"adapter": self.name, "ok": False, "error": e.strerror}


class MinioStorage(Storage):
    name = "minio"

    def __init__(self, url: str, access_key: str, secret_key: str, bucket: str, secure: bool):
        from minio import Minio
        self.client = Minio(url, access_key=access_key, secret_key=secret_key, secure=secure)
        self.bucket = bucket

    def _ensure(self):
        if not self.client.bucket_exists(self.bucket):
            self.client.make_bucket(self.bucket)

    def put(self, key, fileobj, size):
        self._ensure()
        self.client.put_object(self.bucket, self.check_key(key), fileobj, size, content_type="application/octet-stream")

    def open_iter(self, key):
        from minio.error import S3Error
        try:
            r = self.client.get_object(self.bucket, self.check_key(key))
        except S3Error as e:
            raise StorageError(f"object {key}: {e.code}") from None
        try:
            yield from r.stream(CHUNK)
        finally:
            r.close()
            r.release_conn()

    def exists(self, key):
        from minio.error import S3Error
        try:
            self.client.stat_object(self.bucket, self.check_key(key))
            return True
        except S3Error:
            return False

    def delete(self, key):
        self.client.remove_object(self.bucket, self.check_key(key))

    def status(self):
        try:
            self._ensure()
            return {"adapter": self.name, "ok": True, "bucket": self.bucket}
        except Exception as e:  # noqa: BLE001 - report reachability, never credentials
            return {"adapter": self.name, "ok": False, "error": type(e).__name__}


@lru_cache
def get_storage() -> Storage:
    s = get_settings()
    if s.storage_adapter == "minio":
        return MinioStorage(s.minio_url, s.minio_access_key, s.minio_secret_key.get_secret_value(), s.storage_bucket, s.minio_secure)
    return FilesystemStorage(s.storage_dir)
